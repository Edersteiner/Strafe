"""Collects what generators produce and writes it deterministically."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from .model import Header


@dataclass
class _Companion:
    header: Header
    includes: set[str] = field(default_factory=set)
    sections: list[str] = field(default_factory=list)


class Output:
    """Generators add sections to a header's companion `.gen.h`, or whole files."""

    def __init__(self) -> None:
        self._companions: dict[str, _Companion] = {}
        self._files: dict[str, str] = {}

    def section(self, header: Header, text: str, includes: tuple[str, ...] = ()) -> None:
        companion = self._companions.setdefault(header.include_path, _Companion(header))
        companion.includes.update(includes)
        companion.sections.append(text.strip("\n"))

    def ensure_companion(self, header: Header) -> None:
        """Makes sure the header's companion exists, even with nothing in it."""
        _ = self._companions.setdefault(header.include_path, _Companion(header))

    def has_companion(self, header: Header) -> bool:
        return header.include_path in self._companions

    def file(self, relative_path: str, text: str) -> None:
        if relative_path in self._files:
            raise RuntimeError(f"Two generators wrote {relative_path}")
        self._files[relative_path] = text

    def headers_with_companions(self) -> list[Header]:
        return [c.header for c in self._companions.values()]

    def render(self) -> dict[str, str]:
        rendered = dict(self._files)
        for include_path, companion in self._companions.items():
            lines = [
                f"// Generated by strafe_codegen from {companion.header.path}. Do not edit.",
                "#pragma once",
                # Its TypeInfo is only used through templates, which include
                # cleaners can't trace, so they would flag every include of it.
                "// IWYU pragma: always_keep",
            ]
            if companion.includes:
                lines += ["", *(f'#include "{include}"' for include in sorted(companion.includes))]
            for section in companion.sections:
                lines += ["", section]
            rendered[include_path] = "\n".join(lines) + "\n"
        return dict(sorted(rendered.items()))


def write(out_dir: Path, files: dict[str, str]) -> int:
    """Writes files that changed and removes generated files nothing produced.
    Returns how many files were written or removed."""
    changes = 0
    out_dir.mkdir(parents=True, exist_ok=True)
    for relative, text in files.items():
        path = out_dir / relative
        if path.is_file() and path.read_bytes() == text.encode("utf-8"):
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="\n") as stream:
            _ = stream.write(text)
        changes += 1

    for path in sorted(out_dir.rglob("*")):
        if path.is_file() and path.relative_to(out_dir).as_posix() not in files:
            path.unlink()
            changes += 1
    for path in sorted(out_dir.rglob("*"), reverse=True):
        if path.is_dir() and not any(path.iterdir()):
            path.rmdir()
    return changes
