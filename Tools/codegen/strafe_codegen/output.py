"""Collects what generators produce and writes it deterministically."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from .model import Header


@dataclass
class _Companion:
    header: Header
    includes: set[str] = field(default_factory=set)
    sections: list[str] = field(default_factory=list)


REGISTRATION_FILE = "src/register.gen.cpp"


@dataclass
class _Registration:
    """One of the target's registration functions, which run at startup with
    `registry` in scope."""

    function: str
    registry: str  # The C++ type of `registry`.
    statements: list[str] = field(default_factory=list)

    def render(self) -> list[str]:
        if not self.statements:
            return [f"void {self.function}({self.registry} & /* registry */) {{}}"]
        body = [f"  {statement}" for statement in self.statements]
        return [f"void {self.function}({self.registry} &registry) {{", *body, "}"]


class Output:
    """Generators add sections to a header's companion `.gen.h`, statements to the
    target's registration functions, or whole files. Paths are relative to the
    target's generated folder: companions go under include/, sources under src/."""

    def __init__(self, target: str, register_prefix: str) -> None:
        self._target: str = target
        self._companions: dict[str, _Companion] = {}
        self._files: dict[str, str] = {}
        self._registration_includes: set[str] = set()
        self._types: _Registration = _Registration(f"{register_prefix}Types", "reflect::TypeRegistry")
        self._commands: _Registration = _Registration(f"{register_prefix}Commands", "console::CommandRegistry")
        self._components: _Registration = _Registration(f"{register_prefix}Components", "ecs::ComponentRegistry")
        self._systems: _Registration = _Registration(f"{register_prefix}Systems", "ecs::Schedule")

    def section(self, header: Header, text: str, includes: tuple[str, ...] = ()) -> None:
        companion = self._companions.setdefault(header.include_path, _Companion(header))
        companion.includes.update(includes)
        companion.sections.append(text.strip("\n"))

    def ensure_companion(self, header: Header) -> None:
        """Makes sure the header's companion exists, even with nothing in it."""
        _ = self._companions.setdefault(header.include_path, _Companion(header))

    def has_companion(self, header: Header) -> bool:
        return header.include_path in self._companions

    def register_type(self, header: Header, statement: str) -> None:
        """Adds a statement that runs at startup with a TypeRegistry in scope as
        `registry`. The header is included for it."""
        self._registration_includes.add(header.source_include_path)
        self._types.statements.append(statement)

    def register_command(self, header: Header, statement: str) -> None:
        """The same with a CommandRegistry."""
        self._registration_includes.add(header.source_include_path)
        self._commands.statements.append(statement)

    def register_component(self, header: Header, statement: str) -> None:
        """The same with a ComponentRegistry."""
        self._registration_includes.add(header.source_include_path)
        self._components.statements.append(statement)

    def register_system(self, header: Header, statement: str) -> None:
        """The same with a Schedule."""
        self._registration_includes.add(header.source_include_path)
        self._systems.statements.append(statement)

    def file(self, relative_path: str, text: str) -> None:
        if relative_path in self._files:
            raise RuntimeError(f"Two generators wrote {relative_path}")
        self._files[relative_path] = text

    def headers_with_companions(self) -> list[Header]:
        return [c.header for c in self._companions.values()]

    def render(self) -> dict[str, str]:
        rendered = dict(self._files)
        for include_path, companion in self._companions.items():
            lines = [
                f"// Generated by strafe_codegen from {companion.header.path}. Do not edit.",
                "#pragma once",
                # Its TypeInfo is only used through templates, which include
                # cleaners can't trace, so they would flag every include of it.
                "// IWYU pragma: always_keep",
            ]
            if companion.includes:
                lines += ["", *(f'#include "{include}"' for include in sorted(companion.includes))]
            for section in companion.sections:
                lines += ["", section]
            rendered[f"include/{include_path}"] = "\n".join(lines) + "\n"
        rendered[REGISTRATION_FILE] = self._render_registration()
        return dict(sorted(rendered.items()))

    def _render_registration(self) -> str:
        """Always written, even empty, because the engine calls the functions for
        every target."""
        includes = sorted(
            {
                "strafe/console/command.h",
                "strafe/core/type_registry.h",
                "strafe/ecs/component_registry.h",
                "strafe/ecs/system.h",
                *self._registration_includes,
            }
        )
        lines = [
            f"// Generated by strafe_codegen for {self._target}. Do not edit.",
            *(f'#include "{include}"' for include in includes),
            "",
            "#include <utility>",
            "",
            "namespace strafe::generated {",
            "",
            *self._types.render(),
            "",
            *self._commands.render(),
            "",
            *self._components.render(),
            "",
            *self._systems.render(),
            "",
            "} // namespace strafe::generated",
        ]
        return "\n".join(lines) + "\n"


def write(out_dir: Path, files: dict[str, str]) -> int:
    """Writes files that changed and removes generated files nothing produced.
    Returns how many files were written or removed."""
    changes = 0
    out_dir.mkdir(parents=True, exist_ok=True)
    for relative, text in files.items():
        path = out_dir / relative
        if path.is_file() and path.read_bytes() == text.encode("utf-8"):
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="\n") as stream:
            _ = stream.write(text)
        changes += 1

    for path in sorted(out_dir.rglob("*")):
        if path.is_file() and path.relative_to(out_dir).as_posix() not in files:
            path.unlink()
            changes += 1
    for path in sorted(out_dir.rglob("*"), reverse=True):
        if path.is_dir() and not any(path.iterdir()):
            path.rmdir()
    # The build adds include/ as an include directory, and warns when it is missing.
    (out_dir / "include").mkdir(exist_ok=True)
    return changes
